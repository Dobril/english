export type Pattern = 'AAA' | 'ABB' | 'ABC' | 'ABA';

export interface IrregularVerb {
  base: string;
  past: string[];
  participle: string[];
  bg: string;
  core: boolean;
  pattern: Pattern;
}

function patternOf(base: string, past: string, pp: string): Pattern {
  if (base === past && past === pp) return 'AAA';
  if (past === pp) return 'ABB';
  if (base === pp) return 'ABA';
  return 'ABC';
}

const seenBases = new Set<string>();
export const IRREGULAR_VERBS: IrregularVerb[] = rows.filter(([base]) => (seenBases.has(base) ? false : (seenBases.add(base), true))).map(([base, past, pp, bg, core]) => {
  const p = past.split('/');
  const q = pp.split('/');
  return { base, past: p, participle: q, bg, core: core === 1, pattern: patternOf(base, p[0], q[0]) };
});

